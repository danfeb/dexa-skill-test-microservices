DECLARE
table_count NUMBER;
BEGIN
SELECT COUNT(1) INTO table_count
FROM user_tables
WHERE table_name = 'ATD_ATTENDANCE_LOG';

IF table_count = 0 THEN
       EXECUTE IMMEDIATE
            'CREATE TABLE atd_attendance_log (
                id                      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id                 NUMBER NOT NULL,
                employee_id             NUMBER NOT NULL,
                work_type               VARCHAR2(10) NOT NULL,
                attachment              VARCHAR2(255) NOT NULL,
                attendance_datetime     VARCHAR2(14) NOT NULL,
                description             CLOB NOT NULL,
                created_by              VARCHAR2(150) NOT NULL,
                created_at              VARCHAR2(14) NOT NULL,
                updated_by              VARCHAR2(150) NOT NULL,
                updated_at              VARCHAR2(14) NOT NULL
            )';
END IF;
END;
