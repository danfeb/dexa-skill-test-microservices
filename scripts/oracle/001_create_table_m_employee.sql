DECLARE
    table_count NUMBER;
BEGIN
    SELECT COUNT(1) INTO table_count
    FROM user_tables
    WHERE table_name = 'M_EMPLOYEE';

    IF table_count = 0 THEN
       EXECUTE IMMEDIATE
            'CREATE TABLE m_employee (
                id              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                code            VARCHAR2(50) NOT NULL,
                full_name       VARCHAR2(150) NOT NULL,
                date_of_birth   VARCHAR2(50) NOT NULL,
                staff_level     VARCHAR2(10) NOT NULL,
                join_since      VARCHAR2(8) NOT NULL,
                flg_active      CHAR(1) NOT NULL,
                created_by      VARCHAR2(150) NOT NULL,
                created_at      VARCHAR2(14) NOT NULL,
                updated_by      VARCHAR2(150) NOT NULL,
                updated_at      VARCHAR2(14) NOT NULL,
                CONSTRAINT uq_m_employee_code UNIQUE (code)
            )';
    END IF;
END;
