DECLARE
table_count NUMBER;
BEGIN
SELECT COUNT(1) INTO table_count
FROM user_tables
WHERE table_name = 'M_USER';

IF table_count = 0 THEN
       EXECUTE IMMEDIATE
            'CREATE TABLE m_user (
                id              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                employee_id     NUMBER NOT NULL,
                username        VARCHAR2(50) NOT NULL,
                email           VARCHAR2(150) NOT NULL,
                password        VARCHAR2(255) NOT NULL,
                role            VARCHAR2(50) NOT NULL,
                flg_active      CHAR(1) NOT NULL,
                created_by      VARCHAR2(150) NOT NULL,
                created_at      VARCHAR2(14) NOT NULL,
                updated_by      VARCHAR2(150) NOT NULL,
                updated_at      VARCHAR2(14) NOT NULL,
                CONSTRAINT uq_m_user_employee_id UNIQUE (employee_id),
                CONSTRAINT uq_m_user_username UNIQUE (username),
                CONSTRAINT uq_m_user_email UNIQUE (email)
            )';
END IF;
END;
